// Part C — Value vs. Reference Types

Console.WriteLine("Part C — Value vs. Reference Types");
RunPartC();

void RunPartC()
{
    Console.WriteLine("--- Experiment 1: Struct (Value Type) ---");

    Point p1 = new Point { X = 1, Y = 2 };
    Point p2 = p1; // Creates a completely independent copy on the stack

    p2.X = 99; // Modifying p2 does NOT affect p1

    Console.WriteLine("p1.X: " + p1.X);
    Console.WriteLine("p2.X: " + p2.X);
    // Explanation: Point is a struct (Value Type) stored directly on the stack.
    // Assigning p2 = p1 performs a full byte-by-byte copy of the data, so p1 and p2 are independent.


    // Experiment 2 — class reference semantics (Reference Type)
    Console.WriteLine("\n--- Experiment 2: Class (Reference Type) ---");

    Order o1 = new Order
    {
        OrderId = 101,
        CustomerName = "Alice",
        Quantity = 3,
        UnitPrice = 50.0m,
        TotalPrice = 0m,
        IsPaid = false,
        DiscountPercent = 10.0,
        ShippingCity = "Cairo",
        Priority = 'H',
        ItemCode = 9876543210L
    };

    o1.CalculateTotal();

    Order o2 = o1; // Copies the reference (address), not the object itself

    o2.IsPaid = true; // Modifying through o2 affects the same object in the heap

    Console.WriteLine("o1.IsPaid: " + o1.IsPaid);
    Console.WriteLine("o2.IsPaid: " + o2.IsPaid);
    // Explanation: Order is a class (Reference Type) stored on the heap.
    // Assigning o2 = o1 copies only the reference pointer, meaning both variables point to the exact same memory address (shared heap identity).

    object boxedOrder = o1; // No boxing occurs here; Order is already a reference type, so it just stores the reference address.
    Order o3 = (Order)boxedOrder;

    Console.WriteLine("Are o1 and o3 the same instance? " + object.ReferenceEquals(o1, o3));

    // Calling PrintSummary() to verify reflection of change made through o2
    o2.PrintSummary();


    Console.WriteLine("\n--- Explanation Summary ---");
    Console.WriteLine("1. Value types live directly on the Stack (or inline inside heap objects), while reference types have their actual data on the Heap with a pointer stored on the Stack.");
    Console.WriteLine("2. For value types, assignment (=) copies the actual underlying data/value, creating two independent copies.");
    Console.WriteLine("3. For reference types, assignment (=) copies only the memory reference (memory address), so both variables point to the exact same object in heap memory.");
    Console.WriteLine("4. Storing a reference type inside an object variable does not create a new object or trigger boxing; it simply stores the existing object's reference inside a variable of type object.");
}

Console.WriteLine("Break");

