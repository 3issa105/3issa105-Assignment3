    total += 20;
    Console.WriteLine("After += 20: " + total);

    total -= 10;
    Console.WriteLine("After -= 10: " + total);

    total *= 2;
    Console.WriteLine("After *= 2: " + total);

    total /= 4;
    Console.WriteLine("After /= 4: " + total);

    total %= 7;
    Console.WriteLine("After %= 7: " + total);


    Console.WriteLine("\n--- D3: Bitwise Operators ---");
    int a = 12;
    int b = 10;

    Console.WriteLine("a & b: " + (a & b));

    Console.WriteLine("a | b: " + (a | b));

    Console.WriteLine("a ^ b: " + (a ^ b));

    // Difference between & and &&:
    // && stops evaluation if the left operand is false (short-circuit), while & always evaluates both sides.
}

